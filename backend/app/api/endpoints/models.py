@router.get("/metrics")
def get_models_metrics():
    """Returns actual real metrics generated by the training scripts on held-out test data."""
    email_metrics = {}
    login_metrics = {}
    
    if os.path.exists(settings.EMAIL_METRICS_PATH):
        try:
            with open(settings.EMAIL_METRICS_PATH, "r") as f:
                email_metrics = json.load(f)
        except Exception as e:
            email_metrics = {"error": str(e)}
            
    if os.path.exists(settings.LOGIN_METRICS_PATH):
        try:
            with open(settings.LOGIN_METRICS_PATH, "r") as f:
                login_metrics = json.load(f)
        except Exception as e:
            login_metrics = {"error": str(e)}
            
    return {
        "email_model": email_metrics,
        "login_model": login_metrics,
        "disclaimer": (
            "These metrics reflect validation on synthetic campus security telemetry datasets. "
            "Performance on real-world adversaries may vary due to zero-day evasion techniques."
        )
    }
